[[nodiscard]] inline SheenLtcCoefficients sheen_ltc_at(const std::size_t row,
                                                        const std::size_t column) noexcept {
    const std::size_t index = (row * sheen_ltc_resolution + column) * 3;
    constexpr float inv_short_max = 1.0F / 32767.0F;
    return {
        static_cast<float>(sheen_ltc_volume_quantized[index]) *
            sheen_ltc_scales[0] * inv_short_max,
        static_cast<float>(sheen_ltc_volume_quantized[index + 1]) *
            sheen_ltc_scales[1] * inv_short_max,
        static_cast<float>(sheen_ltc_volume_quantized[index + 2]) *
            sheen_ltc_scales[2] * inv_short_max
    };
}

[[nodiscard]] inline SheenLtcCoefficients fetch_sheen_ltc_coefficients(
    const float roughness, const float cos_theta_o) noexcept {
    // The fit is indexed by alpha in [0,1] and cos(theta_o) in [0,1].
    constexpr float max_index = static_cast<float>(sheen_ltc_resolution - 1);
    const float row = std::clamp(roughness, 0.0F, 1.0F) * max_index;
    const float column = std::clamp(cos_theta_o, 0.0F, 1.0F) * max_index;
    const auto row0 = static_cast<std::size_t>(std::floor(row));
    const auto column0 = static_cast<std::size_t>(std::floor(column));
    const auto row1 = std::min(row0 + 1, sheen_ltc_resolution - 1);
    const auto column1 = std::min(column0 + 1, sheen_ltc_resolution - 1);
    const float row_t = row - static_cast<float>(row0);
    const float column_t = column - static_cast<float>(column0);

    const auto c00 = sheen_ltc_at(row0, column0);
    const auto c10 = sheen_ltc_at(row1, column0);
    const auto c01 = sheen_ltc_at(row0, column1);
    const auto c11 = sheen_ltc_at(row1, column1);
    const auto blend = [](const float a, const float b, const float t) noexcept {
        return a + (b - a) * t;
    };
    return {
        blend(blend(c00.a_inv, c10.a_inv, row_t),
              blend(c01.a_inv, c11.a_inv, row_t), column_t),
        blend(blend(c00.b_inv, c10.b_inv, row_t),
              blend(c01.b_inv, c11.b_inv, row_t), column_t),
        blend(blend(c00.reflectance, c10.reflectance, row_t),
              blend(c01.reflectance, c11.reflectance, row_t), column_t)
    };
}

